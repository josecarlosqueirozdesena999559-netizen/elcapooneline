_LEGACY_STATUS_ALIASES = {
    "WAITING_ENTRY_WINDOW": STATUS_WAITING_ENTRY_WINDOW,
}


def normalize_robot_status(status: Any, *, default: str = STATUS_STOPPED) -> str:
    normalized = str(status or "").strip().upper()
    if not normalized:
        return default
    normalized = _LEGACY_STATUS_ALIASES.get(normalized, normalized)
    return normalized if normalized in VALID_ROBOT_STATUSES else default


